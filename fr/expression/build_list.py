#!/usr/bin/env python3
"""
Write fr/expression/expressions.md: the master list of every expression on the flashcard pages.

Pages come in menu order (assets/js/nav-expression-flash.js, CATEGORIES); each page gets its menu
label, its French subtitle, then its sections with French — English for every card. Notes and
examples are left out. The file is regenerated from scratch, so never edit it by hand: change the
page, then rerun this.

Usage (from anywhere):
    python -I fr/expression/build_list.py
"""
import html as htmllib
import json
import re
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")
ROOT = Path(__file__).resolve().parents[2]
PAGES = ROOT / "fr" / "expression"
MENU = ROOT / "assets" / "js" / "nav-expression-flash.js"
OUT = PAGES / "expressions.md"


def read_page(topic):
    """Return (subtitle, categories) from <topic>.html."""
    html = (PAGES / f"{topic}.html").read_text(encoding="utf-8")
    m = re.search(r"const categories = (\[.*?\n\s*\]);", html, re.S)
    if not m:
        sys.exit(f"{topic}.html: no `const categories = [...]` block; the page layout changed")
    js = re.sub(r"(?m)^(\s*)(en|fr|desc|cards):", r'\1"\2":', m.group(1))  # quote the keys
    js = re.sub(r",(\s*[\]}])", r"\1", js)  # drop trailing commas
    sub = re.search(r"</h1>\s*<p[^>]*>\s*(.*?)\s*</p>", html, re.S)
    return (htmllib.unescape(" ".join(sub.group(1).split())) if sub else ""), json.loads(js)


def main():
    menu = re.findall(r'label: "([^"]+)", href: "([\w-]+)\.html"', MENU.read_text(encoding="utf-8"))
    pages = [(label, topic) for label, topic in menu if topic != "archive"]
    toc, body, total = [], [], 0
    for label, topic in pages:
        subtitle, cats = read_page(topic)
        n = sum(len(c["cards"]) for c in cats)
        total += n
        name = label.split(" ", 1)[1]
        anchor = re.sub(r"[^\w]+", "-", name.lower()).strip("-")
        toc.append(f"- [{label}](#{anchor}) — {n}")
        body.append(f'\n<a id="{anchor}"></a>\n\n## {label}\n')
        if subtitle:
            body.append(f"*{subtitle}* · [{topic}.html]({topic}.html) · {n} expressions\n")
        for c in cats:
            body.append(f"\n### {c['en']} — *{c['fr']}*\n")
            body += [f"- **{k[0]}** — {k[1]}" for k in c["cards"]]
    head = [
        "# Les Expressions — Master List",
        "",
        f"{total} expressions on {len(pages)} pages. Generated by `build_list.py` from the pages; "
        "don't edit by hand.",
        "",
        *toc,
    ]
    OUT.write_text("\n".join(head + body) + "\n", encoding="utf-8")
    print(f"{OUT.name}: {total} expressions, {len(pages)} pages")


if __name__ == "__main__":
    main()
